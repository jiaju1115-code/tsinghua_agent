import fs from 'node:fs/promises';
import { SpreadsheetFile, Workbook } from '@oai/artifact-tool';

const root = new URL('..', import.meta.url).pathname.replace(/^\//,'').replace(/\//g,'\\');
const jsonPath = `${root}results\\independent_review_packet.json`;
const outputPath = `${root}results\\independent_review_packet.xlsx`;
const rows = JSON.parse(await fs.readFile(jsonPath,'utf8'));
const headers = ['track','sample_id','query','category','academic_subject','evidence_gate','frozen_evidence','evidence_source_ids','evidence_source_titles','generated_answer','generated_citations','original_correctness_proxy','original_faithfulness_proxy','original_completeness_proxy','original_unsupported_proxy','original_failure_labels','original_primary_failure_type'];
const toCell = (v) => Array.isArray(v) || (v && typeof v === 'object') ? JSON.stringify(v, null, 2) : (v ?? '');
const values = [headers, ...rows.map(r => headers.map(h => toCell(r[h])))];
const wb = Workbook.create();
const sh = wb.worksheets.add('Review Packet');
sh.showGridLines = false;
sh.getRangeByIndexes(0,0,values.length,headers.length).values = values;
const head = sh.getRangeByIndexes(0,0,1,headers.length);
head.format = { fill:'#1F4E78', font:{bold:true,color:'#FFFFFF'}, wrapText:true, horizontalAlignment:'center', verticalAlignment:'center' };
const body = sh.getRangeByIndexes(1,0,rows.length,headers.length);
body.format = { wrapText:true, verticalAlignment:'top', borders:{preset:'inside',style:'thin',color:'#D9E2F3'} };
sh.freezePanes.freezeRows(1);
const widths = [10,12,28,16,16,20,72,24,32,60,20,14,14,18,18,36,24];
for (let i=0;i<widths.length;i++) sh.getRangeByIndexes(0,i,values.length,1).format.columnWidth = widths[i];
sh.getRangeByIndexes(0,0,values.length,headers.length).format.rowHeight = 34;
head.format.rowHeight = 42;
await fs.mkdir(`${root}results`,{recursive:true});
const preview = await wb.render({sheetName:'Review Packet',autoCrop:'all',scale:0.7,format:'png'});
await fs.writeFile(`${root}results\\independent_review_packet_preview.png`,new Uint8Array(await preview.arrayBuffer()));
const xlsx = await SpreadsheetFile.exportXlsx(wb); await xlsx.save(outputPath);
const check = await wb.inspect({kind:'table',sheetId:'Review Packet',range:'A1:Q5',include:'values,formulas',tableMaxRows:5,tableMaxCols:17,tableMaxCellChars:120});
console.log(check.ndjson);
